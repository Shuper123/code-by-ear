        {"table": "products", "columns": ["product_id", "name", "category", "price"],
         "spoken": "The products table has product id, name, category, and price."},
        {"table": "orders", "columns": ["order_id", "customer_id", "order_date", "status"],
         "spoken": "The orders table has order id, customer id, order date, and status."},
        {"table": "order_items", "columns": ["order_id", "product_id", "quantity"],
         "spoken": "The order items table has order id, product id, and quantity."},
