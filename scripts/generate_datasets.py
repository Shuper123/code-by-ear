#!/usr/bin/env python3
"""Generate the two invented practice databases as SQL files (fixed seed, fully reproducible).

factory: parts (12), machines (6), lots (120), defects (200), defect_codes (10)
shop:    customers (40), products (25), orders (150), order_items (400)

Nothing here uses or resembles any employer's data, products or names. Dates are 2026 ISO strings.
Built-in edge cases (spec section 8):
  factory - a lot with no defects (several), a machine with no lots (machine 6), some NULL shifts,
            a defect code never used (D10)
  shop    - a customer with no orders (40), a product never sold (25), cancelled orders

Usage: python3 scripts/generate_datasets.py   (writes src/data/datasets/*.sql and schema.json)
"""
import json
import random
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "data" / "datasets"
SEED = 2026


def sql_value(v):
    if v is None:
        return "NULL"
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    if isinstance(v, float):
        return repr(round(v, 2))
    return str(v)


def insert(table, cols, rows):
    lines = [f"INSERT INTO {table} ({', '.join(cols)}) VALUES"]
    vals = ["  (" + ", ".join(sql_value(v) for v in r) + ")" for r in rows]
    return "\n".join(lines) + "\n" + ",\n".join(vals) + ";\n"


def d(s):
    return date.fromisoformat(s)


def factory(rng):
    parts = [
        # part_id, part_name, line, unit_cost
        (1, "bracket", "A", 2.40),
        (2, "housing", "A", 7.80),
        (3, "gasket", "A", 0.90),
        (4, "clip", "A", 0.25),
        (5, "cover", "B", 3.60),
        (6, "spacer", "B", 0.45),
        (7, "washer", "B", 0.10),
        (8, "bushing", "B", 1.75),
        (9, "plate", "C", 4.20),
        (10, "pin", "C", 0.15),
        (11, "cap", "C", 0.60),
        (12, "seal", "C", 1.20),
    ]
    machines = [
        # machine_id, line, installed_on
        (1, "A", "2026-01-05"),
        (2, "A", "2026-01-12"),
        (3, "B", "2026-01-05"),
        (4, "B", "2026-02-02"),
        (5, "C", "2026-01-19"),
        (6, "C", "2026-03-30"),  # installed late: has no lots
    ]
    codes = [
        # defect_code, description, category
        ("D01", "scratch", "cosmetic"),
        ("D02", "dent", "cosmetic"),
        ("D03", "burr", "dimensional"),
        ("D04", "crack", "structural"),
        ("D05", "warp", "dimensional"),
        ("D06", "short shot", "structural"),
        ("D07", "flash", "cosmetic"),
        ("D08", "porosity", "structural"),
        ("D09", "misalignment", "dimensional"),
        ("D10", "discoloration", "cosmetic"),  # never used
    ]
    line_machines = {"A": [1, 2], "B": [3, 4], "C": [5]}
    part_line = {p[0]: p[2] for p in parts}

    # First lots are hand-picked so drills can state facts about them.
    lots = [
        # lot_id, part_id, machine_id, produced_on, qty, shift
        (1, 1, 1, "2026-01-06", 120, "day"),
        (2, 2, 2, "2026-01-06", 340, "night"),
        (3, 5, 3, "2026-01-07", 90, "day"),
        (4, 9, 5, "2026-01-07", 200, None),
        (5, 1, 2, "2026-01-08", 120, "night"),  # ties lot 1 on purpose (RANK drills)
    ]
    start = d("2026-01-09")
    for lot_id in range(6, 121):
        part_id = rng.randint(1, 12)
        machine_id = rng.choice(line_machines[part_line[part_id]])
        produced = start + timedelta(days=(lot_id - 6) * 80 // 115)
        qty = rng.randrange(60, 510, 10)
        shift = rng.choice(["day", "night"])
        if lot_id in (17, 44, 71, 98, 115):
            shift = None
        lots.append((lot_id, part_id, machine_id, produced.isoformat(), qty, shift))

    lot_date = {l[0]: d(l[3]) for l in lots}
    used_codes = [c[0] for c in codes if c[0] != "D10"]
    weights = [9, 7, 6, 2, 5, 3, 6, 2, 4]
    # lots that never get a defect (edge case "a lot with no defects"; lot 3 is one of them)
    clean_lots = {3, 12, 25, 33, 47, 58, 66, 80, 91, 104, 117}
    defect_lots = [l for l in lot_date if l not in clean_lots]
    defects = [
        # defect_id, lot_id, defect_code, qty, found_on
        (1, 1, "D01", 4, "2026-01-06"),
        (2, 1, "D03", 2, "2026-01-07"),
        (3, 2, "D04", 1, "2026-01-07"),
        (4, 5, "D01", 6, "2026-01-08"),
    ]
    for defect_id in range(5, 201):
        lot_id = rng.choice(defect_lots)
        code = rng.choices(used_codes, weights=weights)[0]
        qty = rng.randint(1, 12)
        found = lot_date[lot_id] + timedelta(days=rng.randint(0, 3))
        defects.append((defect_id, lot_id, code, qty, found.isoformat()))

    ddl = """-- factory: invented quality data for Code by Ear. Generated by scripts/generate_datasets.py (seed 2026).
CREATE TABLE parts (part_id INTEGER PRIMARY KEY, part_name TEXT NOT NULL, line TEXT NOT NULL, unit_cost REAL NOT NULL);
CREATE TABLE machines (machine_id INTEGER PRIMARY KEY, line TEXT NOT NULL, installed_on TEXT NOT NULL);
CREATE TABLE lots (lot_id INTEGER PRIMARY KEY, part_id INTEGER NOT NULL REFERENCES parts(part_id), machine_id INTEGER NOT NULL REFERENCES machines(machine_id), produced_on TEXT NOT NULL, qty INTEGER NOT NULL, shift TEXT);
CREATE TABLE defect_codes (defect_code TEXT PRIMARY KEY, description TEXT NOT NULL, category TEXT NOT NULL);
CREATE TABLE defects (defect_id INTEGER PRIMARY KEY, lot_id INTEGER NOT NULL REFERENCES lots(lot_id), defect_code TEXT NOT NULL REFERENCES defect_codes(defect_code), qty INTEGER NOT NULL, found_on TEXT NOT NULL);
"""
    body = (
        insert("parts", ["part_id", "part_name", "line", "unit_cost"], parts)
        + insert("machines", ["machine_id", "line", "installed_on"], machines)
        + insert("lots", ["lot_id", "part_id", "machine_id", "produced_on", "qty", "shift"], lots)
        + insert("defect_codes", ["defect_code", "description", "category"], codes)
        + insert("defects", ["defect_id", "lot_id", "defect_code", "qty", "found_on"], defects)
    )
    return ddl + body


def shop(rng):
    first = ["Ana", "Ben", "Cara", "Dev", "Eli", "Fay", "Gus", "Hana", "Ivan", "Jo", "Kai", "Lia", "Max", "Nia",
             "Omar", "Pia", "Quinn", "Rosa", "Sam", "Tess", "Uma", "Vic", "Wes", "Xena", "Yuri", "Zoe", "Abe",
             "Bea", "Cy", "Dina", "Ezra", "Flo", "Gil", "Hal", "Ines", "Jude", "Kit", "Lev", "Mae", "Ned"]
    last = ["Park", "Reyes", "Stone", "Moss", "Hale", "Cruz", "Lane", "Ford", "Kim", "West"]
    cities = ["Riverton", "Fairview", "Lakeside", "Hillcrest", "Oakdale"]
    customers = []
    for i in range(1, 41):
        name = f"{first[i - 1]} {last[(i * 7) % len(last)]}"
        city = cities[(i - 1) % len(cities)] if i > 5 else ["Riverton", "Fairview", "Riverton", "Lakeside", "Oakdale"][i - 1]
        signup = (d("2026-01-02") + timedelta(days=(i - 1) * 2)).isoformat()
        customers.append((i, name, city, signup))

    products = [
        # product_id, name, category, price
        (1, "notebook", "office", 4.50), (2, "pen", "office", 1.20), (3, "stapler", "office", 12.00),
        (4, "desk lamp", "office", 28.00), (5, "folder", "office", 2.75), (6, "mug", "kitchen", 9.00),
        (7, "kettle", "kitchen", 35.00), (8, "cutting board", "kitchen", 18.50), (9, "spatula", "kitchen", 6.25),
        (10, "teapot", "kitchen", 24.00), (11, "towel", "home", 11.00), (12, "pillow", "home", 19.00),
        (13, "candle", "home", 7.50), (14, "clock", "home", 22.00), (15, "rug", "home", 45.00),
        (16, "tent", "outdoor", 120.00), (17, "lantern", "outdoor", 26.00), (18, "water bottle", "outdoor", 14.00),
        (19, "backpack", "outdoor", 55.00), (20, "folding chair", "outdoor", 32.00), (21, "tape", "office", 3.10),
        (22, "bowl", "kitchen", 8.00), (23, "blanket", "home", 38.00), (24, "compass", "outdoor", 16.00),
        (25, "label maker", "office", 42.00),  # never sold
    ]

    orders = [
        # order_id, customer_id, order_date, status
        (1, 1, "2026-02-01", "shipped"),
        (2, 1, "2026-02-03", "shipped"),
        (3, 2, "2026-02-03", "cancelled"),
        (4, 3, "2026-02-04", "pending"),
    ]
    for oid in range(5, 151):
        cust = rng.randint(1, 39)  # customer 40 never orders
        od = d("2026-02-04") + timedelta(days=(oid - 5) * 85 // 146)
        status = rng.choices(["shipped", "pending", "cancelled"], weights=[75, 13, 12])[0]
        orders.append((oid, cust, od.isoformat(), status))

    # 400 items: fixed ones for the first orders, then fill to exactly 400 with unique products per order
    items = [(1, 1, 3), (1, 2, 10), (2, 6, 2), (3, 7, 1), (4, 16, 1), (4, 18, 2)]
    per_order = {o[0]: set() for o in orders}
    for oid, pid, _ in items:
        per_order[oid].add(pid)
    order_ids = [o[0] for o in orders if o[0] > 4]
    # every remaining order gets at least one item
    for oid in order_ids:
        pid = rng.randint(1, 24)
        per_order[oid].add(pid)
        items.append((oid, pid, rng.randint(1, 5)))
    while len(items) < 400:
        oid = rng.choice(order_ids)
        if len(per_order[oid]) >= 5:
            continue
        pid = rng.randint(1, 24)
        if pid in per_order[oid]:
            continue
        per_order[oid].add(pid)
        items.append((oid, pid, rng.randint(1, 5)))
    items.sort()

    ddl = """-- shop: invented store data for Code by Ear. Generated by scripts/generate_datasets.py (seed 2026).
CREATE TABLE customers (customer_id INTEGER PRIMARY KEY, name TEXT NOT NULL, city TEXT NOT NULL, signup_date TEXT NOT NULL);
CREATE TABLE products (product_id INTEGER PRIMARY KEY, name TEXT NOT NULL, category TEXT NOT NULL, price REAL NOT NULL);
CREATE TABLE orders (order_id INTEGER PRIMARY KEY, customer_id INTEGER NOT NULL REFERENCES customers(customer_id), order_date TEXT NOT NULL, status TEXT NOT NULL);
CREATE TABLE order_items (order_id INTEGER NOT NULL REFERENCES orders(order_id), product_id INTEGER NOT NULL REFERENCES products(product_id), quantity INTEGER NOT NULL, PRIMARY KEY (order_id, product_id));
"""
    body = (
        insert("customers", ["customer_id", "name", "city", "signup_date"], customers)
        + insert("products", ["product_id", "name", "category", "price"], products)
        + insert("orders", ["order_id", "customer_id", "order_date", "status"], orders)
        + insert("order_items", ["order_id", "product_id", "quantity"], items)
    )
    return ddl + body


